DAYS = {'D': 'wf', 'S': 'w', '67': 'sh'}
mins = lambda t: int(t[:2]) * 60 + int(t[3:])
hm = lambda m: '%02d:%02d' % divmod(m, 60)


def main():
    D = json.load(open(OUT, encoding='utf-8'))
    old = [t for t in D['trips'] if t['line'] == 'RX']
    full = max(old, key=lambda t: len(t['st']))   # the full route Szczawnik -> Nowy Sącz, with its running times
    assert full['st'][0][0] == 'km16' and full['st'][-1][0] == 'kmx11', full['st'][0]
    seq = [s for s, _ in full['st']]; base = mins(full['st'][0][1])
    off = {s: mins(t) - base for s, t in full['st']}
    trips = []
    for runs, cols, to_sz in ((RUNS_NS, TO_NS, False), (RUNS_SZ, TO_SZ, True)):
        sq = seq[::-1] if to_sz else seq
        of = {k: -v for k, v in off.items()} if to_sz else off
        for code, row in runs:
            w = code.endswith('w'); code = code.rstrip('w')
            tp = [(sid, v[:2] + ':' + v[2:]) for sid, v in zip(cols, row.split(',')) if v]
            assert len(row.split(',')) == len(cols), (code, row)
            st = [list(tp[0])]
            for (a, ta), (b, tb) in zip(tp, tp[1:]):
                assert mins(tb) >= mins(ta), (a, ta, b, tb)
                ia, ib = sq.index(a), sq.index(b)
                for c in sq[ia + 1:ib]:
                    f = (of[c] - of[a]) / (of[b] - of[a]) if of[b] != of[a] else 0
                    st.append([c, hm(round(mins(ta) + f * (mins(tb) - mins(ta))))])
                st.append([b, tb])
            if w:   # Szczawnik wyciąg: Szczawnik nad Potokiem 1 min, Stacja Narciarska 2 min from Szczawnik
                if to_sz and st[-1][0] == 'km16': st += [['km15', hm(mins(st[-1][1]) + 1)], ['km14', hm(mins(st[-1][1]) + 2)]]
                elif not to_sz and st[0][0] == 'km16': st = [['km14', hm(mins(st[0][1]) - 2)], ['km15', hm(mins(st[0][1]) - 1)]] + st
            trips.append({'line': 'RX', 'days': DAYS[code], 'src': SRC['sz' if to_sz else 'ns'], 'st': st})
    trips += [dict(t, line='RXN') for t in trips]
    D['trips'] = [t for t in D['trips'] if t['line'] not in ('RX', 'RXN')] + trips
    for k in ('km14', 'km15'):
        if k not in D['stops']:
            D['stops'][k] = json.load(open(os.path.join(os.path.dirname(OUT), 'krynica_muszyna.json'), encoding='utf-8'))['stops'][k]
    json.dump(D, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('RX1:', len(trips) // 2, 'kursów')


if __name__ == '__main__':
    main()
